"""A catalogue per publisher (T-4596, EP-127, API/08 sections 5 and 6): each seeded Project names
its body by its registry IRI and the installation's desk, and the public Endpoints of Banská
Bystrica and Praha declare what the Slovak and Czech profiles ask, leaving the publisher to the
Project so the record carries the registry IRI and not a web site."""

import re
from pathlib import Path

import yaml

SEED = Path(__file__).resolve().parent.parent / "components/context-gateway/seed"
SK = "https://data.gov.sk/id/legal-subject/"
CZ = "https://rpp-opendata.egon.gov.cz/odrpp/zdroj/orgán-veřejné-moci/"
PUBLISHERS = {
    "banskabystrica": SK + "00313271",
    "bbsk": SK + "37828100",
    "zilina": SK + "00321796",
    "praha": CZ + "00064581",
}
LAW_106 = "https://www.e-sbirka.cz/eli/cz/sb/1999/106/2025-08-19"


def manifests():
    for path in SEED.rglob("*.yaml"):
        if path.name == "index.yaml" or path.name.endswith(".linkml.yaml") or ".enc." in path.name:
            continue
        for doc in yaml.safe_load_all(path.read_text()):
            if isinstance(doc, dict) and doc.get("kind") in {"Project", "Endpoint"}:
                yield path, doc


def test_each_project_names_its_body_by_its_registry_iri_and_the_installation_desk():
    projects = {d["metadata"]["name"]: d for _, d in manifests() if d["kind"] == "Project"}
    for name, iri in PUBLISHERS.items():
        catalog = projects[name]["spec"]["catalog"]
        assert catalog["publisher"]["uri"] == iri, name
        assert re.fullmatch(r"\d{8}", iri.rsplit("/", 1)[1]), iri
        assert catalog["publisher"]["name"], name
        assert catalog["contactPoint"] == {"name": "joinedcontext platform", "email": "hello@joinedcontext.com"}


def test_the_public_catalogued_endpoints_of_bb_and_praha_complete_their_profile():
    language = {"banskabystrica": "sk", "praha": "cs"}
    nuts = {"banskabystrica": "SK032", "praha": "CZ010"}
    checked = 0
    for path, d in manifests():
        project = d["metadata"].get("namespace")
        spec = d["spec"]
        if d["kind"] != "Endpoint" or project not in language or spec.get("audience") != "public":
            continue
        if spec.get("callerRole"):
            continue  # an App's door, generated by the Portal, is not one of the publisher's datasets
        catalog = spec.get("catalog")
        assert catalog, f"{path.name}: a public Endpoint of {project} declares no catalogue"
        lang = language[project]
        assert d["metadata"]["description"].get(lang), path.name
        assert catalog["keywords"].get(lang), path.name
        assert catalog["themes"] and catalog["frequency"], path.name
        # Every dataset names its licence, except one read only from Golemio: its terms allow
        # republishing but grant no sublicence, so the record claims none (owner 2026-10-22, T-5268).
        golemio = all(s["url"].startswith("https://api.golemio.cz/") for s in catalog.get("source", []))
        assert catalog.get("license") or (golemio and catalog.get("source")), path.name
        assert nuts[project] in catalog["spatial"], path.name
        assert catalog["personalData"] in {"contains", "does-not-contain"}, path.name
        # The Project's registry IRI is the record's publisher only where the Endpoint names none.
        assert "publisher" not in catalog and "contactPoint" not in catalog, path.name
        if project == "praha":
            assert LAW_106 in catalog["applicableLegislation"], path.name
        checked += 1
    assert checked >= 16, checked
