#!/usr/bin/env python3
"""Writes the Decidim harvesters of slovensko-participacia from instances.csv (T-5065).

One row of instances.csv is one Decidim instance: generate.py writes its DataSource (the instance as the
run's input), its daily Pipeline, its hourly budgets-only Pipeline, both mappings (a copy of pipeline.yaml),
the index lines, the catalogue source and the dataset's title and CKAN organization. `generate.py --check` fails when a written file differs.
"""
import csv
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SEED = ROOT / "components/context-gateway/seed/slovensko"
NS = "slovensko"
SPACE = "slovensko-participacia"
TARGET = f"urn:ngsi-ld:Endpoint:joinedcontext.com:{SPACE}:{SPACE}-zapis"
HEADER = (
    "# Generated by seeds/decidim/generate.py from the row {name} of instances.csv (T-5065).\n"
    "# Do not edit: change seeds/decidim/pipeline.yaml or the CSV and rerun generate.py.\n"
)
INDEX_BEGIN = "# BEGIN generated by seeds/decidim/generate.py (T-5065): the Decidim harvesters of slovensko-participacia"
INDEX_END = "# END generated by seeds/decidim/generate.py"
SOURCES_BEGIN = "    # BEGIN sources generated by seeds/decidim/generate.py: do not edit by hand"
SOURCES_END = "    # END sources generated by seeds/decidim/generate.py"
TITLE_BEGIN = "  # BEGIN title generated by seeds/decidim/generate.py: do not edit by hand"
TITLE_END = "  # END title generated by seeds/decidim/generate.py"
ORGANIZATION_BEGIN = "      # BEGIN organization generated by seeds/decidim/generate.py: do not edit by hand"
ORGANIZATION_END = "      # END organization generated by seeds/decidim/generate.py"
NAME = re.compile(r"^[a-z0-9]([a-z0-9-]{0,40}[a-z0-9])?$")
# A CKAN organization slug (EP-65); empty leaves the dataset in the instance's organization.
ORGANIZATION = re.compile(r"^([a-z0-9][a-z0-9_-]{1,99})?$")
SCOPE = re.compile(r"^(/[A-Za-z0-9_]+)+$")
BASE = re.compile(r"^https://[a-z0-9.-]+\.[a-z]{2,}$")
# The classes the full pass writes (pipeline.yaml's `type` table); the light pass writes BudgetProject alone.
TYPES = ("ParticipatoryProcess", "Proposal", "BudgetProject", "Result", "Meeting", "Debate", "Survey")
# A pass: (suffix, light, schedule, period, title suffix sk, en).
PASSES = (
    ("", False, "{m} 2 * * *", "24h", "", ""),
    ("-hlasovanie", True, "{m} * * * *", "1h", " (hlasovanie)", " (voting)"),
)


def rows() -> list[dict]:
    with (HERE / "instances.csv").open(encoding="utf-8") as f:
        found = list(csv.DictReader(f))
    for row in found:
        if not NAME.match(row["name"]) or not BASE.match(row["base_url"]) or not SCOPE.match(row["scope"]):
            raise SystemExit(f"instances.csv: row {row['name']!r} needs a lowercase name, an https base URL without a path and a scope /SK/XX/town")
        if not ORGANIZATION.match(row["organization"]):
            raise SystemExit(f"instances.csv: row {row['name']!r} needs a CKAN organization slug such as banskabystrica, or none")
    return found


def q(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def documents(i: int, row: dict) -> dict[str, str]:
    files = {}
    mapping = (HERE / "pipeline.yaml").read_text()
    host = row["base_url"].removeprefix("https://")
    for suffix, light, schedule, period, sk, en in PASSES:
        name = f"decidim-{row['name']}{suffix}"
        cfg = {
            "instance": row["name"], "base": row["base_url"], "locale": row["locale"], "scope": row["scope"],
            "locality": row["locality"], "provider": row["provider"], "light": light,
        }
        head = HEADER.format(name=row["name"])
        files[f"{NS}-datasource-{name}.yaml"] = head + f"""apiVersion: joinedcontext.com/v1alpha1
kind: DataSource
metadata:
  name: {name}
  namespace: {NS}
  title:
    sk: {q(f"Decidim: {host}{sk}")}
    en: {q(f"Decidim: {host}{en}")}
spec:
  type: generate
  input:
    # The instance this run reads; the mapping (pipeline.yaml) builds every URL from base alone.
    mapping: {q("root = " + json.dumps(cfg, ensure_ascii=False))}
    count: 1
    interval: ""
"""
        files[f"{NS}-pipeline-{name}.yaml"] = head + f"""apiVersion: joinedcontext.com/v1alpha1
kind: Pipeline
metadata:
  name: {name}
  namespace: {NS}
  title:
    sk: {q(f"Participácia: {row['locality']}{sk}")}
    en: {q(f"Participation: {row['locality']}{en}")}
spec:
  class: auto
  period: {period}
  schedule: "{schedule.format(m=(7 + 11 * i) % 60)}"
  source:
    dataSourceRef: {{ kind: DataSource, name: {name} }}
  targetEndpoint: {TARGET}
  output:
    # Seven types (the model's classes); the type named here is the one every run writes.
    type: {"BudgetProject" if light else "ParticipatoryProcess"}
    mode: upsert
  quotas:
    maxMemoryMb: 256
    cpuMillicores: 100
"""
        # The base is a literal in every http step (PL-07); BASE above keeps it a bare https host.
        files[f"{NS}-pipeline-{name}-bento.yaml"] = head + mapping.replace("__BASE__", row["base_url"])
        if not light:
            files[f"{NS}-policy-{name}-account.yaml"] = head + policy(name)
    return files


def policy(name: str) -> str:
    """The full pass writes every class of the model, its derived Policy grants only the output's one
    type (PL-20): this one grants its account all seven, on its space alone (T-5717)."""
    types = "".join(f"        - type: {t}\n" for t in TYPES)
    return f"""apiVersion: joinedcontext.com/v1alpha1
kind: Policy
metadata:
  name: {name}-account
  namespace: {NS}
  title:
    sk: {q(f"Kanál {name} zapisuje všetky triedy participácie")}
    en: {q(f"The {name} pipeline writes every participation class")}
spec:
  contextSpaceRef: {{ kind: ContextSpace, name: {SPACE} }}
  assigner: did:web:joinedcontext.com
  assignee: {{ kind: serviceAccount, id: pl-{name} }}
  operations: [upsertBatch, createBatch, queryBatch]
  information:
    - entities:
{types}"""


def index_lines(found: list[dict]) -> list[str]:
    out = []
    for row in found:
        for suffix, *_ in PASSES:
            name = f"decidim-{row['name']}{suffix}"
            out += [
                f"{NS}-datasource-{name}.yaml: projects/{NS}/datasources/{name}.yaml",
                f"{NS}-pipeline-{name}.yaml: projects/{NS}/pipelines/{name}/pipeline.yaml",
                f"{NS}-pipeline-{name}-bento.yaml: projects/{NS}/pipelines/{name}/bento.yaml",
            ]
            if not suffix:
                out.append(f"{NS}-policy-{name}-account.yaml: projects/{NS}/spaces/{SPACE}/policies/{name}-account.yaml")
    return out


def sources(found: list[dict]) -> list[str]:
    out = ["    source:"]
    for row in found:
        out += [
            f"      - url: {q(row['base_url'] + '/')}",
            f"        title: {{ sk: {q(row['provider'])}, en: {q(row['provider'])} }}",
            "        description:",
            f"          sk: {q('Participatívna platforma Decidim ' + row['version'] + ', čítaná cez verejné GraphQL API ' + row['base_url'] + '/api.')}",
            f"          en: {q('Decidim ' + row['version'] + ' participation platform, read through its public GraphQL API ' + row['base_url'] + '/api.')}",
        ]
    return out


def title(found: list[dict]) -> list[str]:
    """The dataset title: the town while one instance feeds it, Slovakia once several do (T-6098)."""
    if len(found) == 1:
        town = found[0]["locality"]
        return [f"  title: {{ sk: {q('Participácia občanov, ' + town)}, en: {q('Citizen participation, ' + town)} }}"]
    return ['  title: { sk: "Participácia občanov na Slovensku", en: "Citizen participation in Slovakia" }']


def organization(found: list[dict]) -> list[str]:
    """The town's CKAN organization while it is the only instance; the slovensko one otherwise (T-6098)."""
    if len(found) == 1 and found[0]["organization"]:
        return [f"      organization: {found[0]['organization']}"]
    return []


def with_block(text: str, begin: str, end: str, block: list[str]) -> str:
    if begin not in text:
        return text.rstrip("\n") + "\n" + "\n".join([begin, *block, end]) + "\n"
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    return head + "\n".join([begin, *block, end]) + tail


def wanted() -> tuple[dict[Path, str], list[Path]]:
    found = rows()
    files = {}
    for i, row in enumerate(found):
        files.update({SEED / k: v for k, v in documents(i, row).items()})
    index = SEED / "index.yaml"
    files[index] = with_block(index.read_text(), INDEX_BEGIN, INDEX_END, index_lines(found))
    endpoint = SEED / f"{NS}-endpoint-participacia.yaml"
    text = with_block(endpoint.read_text(), SOURCES_BEGIN, SOURCES_END, sources(found))
    text = with_block(text, TITLE_BEGIN, TITLE_END, title(found))
    files[endpoint] = with_block(text, ORGANIZATION_BEGIN, ORGANIZATION_END, organization(found))
    stale = [p for p in SEED.glob(f"{NS}-*-decidim-*.yaml") if p not in files]
    return files, stale


def main(check: bool) -> int:
    files, stale = wanted()
    differ = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
    if check:
        for p in differ + stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        return 1 if differ or stale else 0
    for p in differ:
        p.write_text(files[p])
    for p in stale:
        p.unlink()
    print(f"wrote {len(differ)} files, removed {len(stale)}")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv[1:]))
