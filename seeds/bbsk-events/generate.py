#!/usr/bin/env python3
"""Write one DataSource, Pipeline and mapping per kept events source (T-4896).

Reads sources.csv (T-4894's inventory) and venues.csv (venues checked by hand), takes the rows
whose decision is `pipeline` and whose feed kind has a template under pipelines/, and writes
components/context-gateway/seed/bbsk/bbsk-{datasource,pipeline}-podujatia-<name>.yaml and its -bento.yaml plus
their lines in that folder's index.yaml. `--check` writes nothing and fails when a file differs.

Run: python3 seeds/bbsk-events/generate.py [--check]
"""

import csv
import json
import re
import sys
import unicodedata
from pathlib import Path
from urllib.parse import urlsplit

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SEED = ROOT / "components/context-gateway/seed/bbsk"
INDEX = SEED / "index.yaml"
TARGET = "urn:ngsi-ld:Endpoint:bbsk.sk:bbsk-podujatia:bbsk-podujatia-slovensko"
UA = "joinedcontext-platform/1.0 (+https://dev.joinedcontext.com; public events)"
REGION = "Banskobystrický kraj"
#: feed kind of the inventory -> template file under pipelines/.
TEMPLATES = {
    "wp-rest-sc": "wp-rest-sc",
    "tribe-rest": "tribe-rest",
    "ical": "ical",
    "weby-feed": "weby-feed",
    "mec-rest": "mec-jsonld",
}
#: Fewer bytes per run: the fields the template reads (WordPress `_fields`).
TRIM = {"wp-rest-sc": "_fields=id,link,title,content,modified_gmt,meta_box"}
INDEX_BEGIN = (
    "# BEGIN generated by seeds/bbsk-events/generate.py (T-4896): do not edit by hand"
)
INDEX_END = "# END generated by seeds/bbsk-events/generate.py"


class Dumper(yaml.SafeDumper):
    """Writes a multi-line string (a mapping) as a literal block, so it reads as written."""


Dumper.add_representer(
    str,
    lambda d, v: d.represent_scalar(
        "tag:yaml.org,2002:str", v, style="|" if "\n" in v else None
    ),
)


def slug(text: str) -> str:
    ascii_ = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", ascii_.lower()).strip("-")


def kept_sources() -> list[dict]:
    rows = [r for r in csv.DictReader((HERE / "sources.csv").open(encoding="utf-8"))]
    kept = [
        r for r in rows if r["decision"] == "pipeline" and r["feed_kind"] in TEMPLATES
    ]
    for row in kept:
        parts = urlsplit(row["check_url"])
        assert parts.scheme == "https" and re.fullmatch(
            r"[a-z0-9.-]+", parts.hostname or ""
        ), row["check_url"]
        labels = parts.hostname.removeprefix("www.").split(".")
        row["name"] = "podujatia-" + labels[0]
        row["host"] = f"https://{parts.hostname}"
        row["town_slug"] = None if row["town"] == REGION else slug(row["town"])
    names = [r["name"] for r in kept]
    assert len(names) == len(set(names)), names
    return kept


def venues_for(town_slug: str | None) -> list[dict]:
    out = []
    for v in csv.DictReader((HERE / "venues.csv").open(encoding="utf-8")):
        if v["town"] != town_slug and not (town_slug is None and v["regional"] == "y"):
            continue
        out.append(
            {
                "match": v["match"],
                "town": v["town"],
                "venue": v["venue"],
                "streetAddress": v["streetAddress"] or None,
                "addressLocality": v["addressLocality"],
                "lat": float(v["lat"]),
                "lon": float(v["lon"]),
            }
        )
    return out


def processors(row: dict) -> list:
    """The template's steps then the common tail, each __NAME__ a JSON literal."""
    facts_only = not row["licence_terms"].startswith("CC-BY")
    values = {
        "__VENUES__": json.dumps(
            venues_for(row["town_slug"]), ensure_ascii=False, separators=(",", ":")
        ),
        "__TOWN__": json.dumps(
            None if row["town_slug"] is None else row["town"], ensure_ascii=False
        ),
        "__TOWN_SLUG__": json.dumps(row["town_slug"]),
        "__SOURCE__": json.dumps(row["events_url"], ensure_ascii=False),
        "__PROVIDER__": json.dumps(provider(row), ensure_ascii=False),
        "__FACTS_ONLY__": "true" if facts_only else "false",
        "__HOST_RE__": re.escape(row["host"]).replace("\\", "\\\\"),
        "__HOST__": row["host"],
    }
    text = (HERE / "pipelines" / f"{TEMPLATES[row['feed_kind']]}.yaml").read_text(
        encoding="utf-8"
    )
    text += (HERE / "pipelines/common.yaml").read_text(encoding="utf-8")
    for name, value in values.items():
        text = text.replace(name, value)
    assert not re.search(r"__[A-Z_]+__", text), row["name"]
    return yaml.safe_load(text)


def provider(row: dict) -> str:
    host = urlsplit(row["events_url"]).hostname.removeprefix("www.")
    licence = (
        row["licence_terms"].split(" ")[0]
        if row["licence_terms"].startswith("CC-")
        else "licencia neuvedená"
    )
    return f"{row['town']}, {host} ({licence})"


def documents(index: int, row: dict) -> dict[str, str]:
    name, town = row["name"], row["town"]
    url = row["check_url"]
    if row["feed_kind"] in TRIM:
        url += ("&" if "?" in url else "?") + TRIM[row["feed_kind"]]
    # One run a day, staggered over 00:00-02:34 UTC, which is 01:00-05:00 in Bratislava in winter
    # and in summer (owner 2026-10-20), so no two sources start in the same minute.
    minute = index * 11
    datasource = {
        "apiVersion": "joinedcontext.com/v1alpha1",
        "kind": "DataSource",
        "metadata": {
            "name": name,
            "namespace": "bbsk",
            "title": {
                "sk": f"Podujatia: {town} ({row['feed_kind']})",
                "en": f"Events: {town} ({row['feed_kind']})",
            },
        },
        "spec": {
            "type": "http",
            "http": {
                "url": url,
                "verb": "GET",
                "headers": {"User-Agent": UA, "Accept": accept(row["feed_kind"])},
                "timeout": "30s",
            },
        },
    }
    pipeline = {
        "apiVersion": "joinedcontext.com/v1alpha1",
        "kind": "Pipeline",
        "metadata": {
            "name": name,
            "namespace": "bbsk",
            "title": {"sk": f"Podujatia: {town}", "en": f"Events: {town}"},
        },
        "spec": {
            "class": "auto",
            "period": "24h",
            "schedule": f"{minute % 60} {minute // 60} * * *",
            "source": {"dataSourceRef": {"kind": "DataSource", "name": name}},
            "targetEndpoint": TARGET,
            "output": {"type": "Event", "mode": "upsert"},
            "quotas": {"maxMemoryMb": 128, "cpuMillicores": 100},
        },
    }
    head = (
        f"# Generated by seeds/bbsk-events/generate.py from sources.csv row {town} ({row['feed_kind']}),\n"
        f"# read {row['read_on']}: {row['events_url']} (T-4896). Do not edit: change the template or the CSV.\n"
    )
    bento = {"pipeline": {"processors": processors(row)}}
    dump = lambda d: yaml.dump(
        d, Dumper=Dumper, allow_unicode=True, sort_keys=False, width=120
    )
    return {
        f"bbsk-datasource-{name}.yaml": head + dump(datasource),
        f"bbsk-pipeline-{name}.yaml": head + dump(pipeline),
        f"bbsk-pipeline-{name}-bento.yaml": head + dump(bento),
    }


def accept(kind: str) -> str:
    return {
        "ical": "text/calendar",
        "weby-feed": "application/rss+xml, application/atom+xml, application/xml",
    }.get(kind, "application/json")


def index_lines(rows: list[dict]) -> list[str]:
    lines = [INDEX_BEGIN]
    for row in rows:
        lines += [
            f"bbsk-datasource-{row['name']}.yaml: projects/bbsk/datasources/{row['name']}.yaml",
            f"bbsk-pipeline-{row['name']}.yaml: projects/bbsk/pipelines/{row['name']}/pipeline.yaml",
            f"bbsk-pipeline-{row['name']}-bento.yaml: projects/bbsk/pipelines/{row['name']}/bento.yaml",
        ]
    return lines + [INDEX_END]


def main(check: bool) -> int:
    rows = kept_sources()
    wanted: dict[Path, str] = {}
    for i, row in enumerate(rows):
        for file, text in documents(i, row).items():
            wanted[SEED / file] = text
    index = INDEX.read_text(encoding="utf-8")
    block = "\n".join(index_lines(rows)) + "\n"
    if INDEX_BEGIN in index:
        index = re.sub(
            re.escape(INDEX_BEGIN) + r".*?" + re.escape(INDEX_END) + "\n",
            lambda _: block,
            index,
            flags=re.DOTALL,
        )
    else:
        index = index.rstrip("\n") + "\n" + block
    wanted[INDEX] = index
    ours = [
        *SEED.glob("bbsk-datasource-podujatia-*.yaml"),
        *SEED.glob("bbsk-pipeline-podujatia-*.yaml"),
    ]
    stale = [p for p in ours if p not in wanted]
    differ = [
        p
        for p, t in wanted.items()
        if not p.is_file() or p.read_text(encoding="utf-8") != t
    ]
    if check:
        for p in differ + stale:
            print(f"out of date: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1 if differ or stale else 0
    for p in stale:
        p.unlink()
    for p in differ:
        p.write_text(wanted[p], encoding="utf-8")
    print(f"{len(rows)} sources, {len(differ)} files written, {len(stale)} removed")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv[1:]))
