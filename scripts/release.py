#!/usr/bin/env python3
"""Releases of the deployment: cut a tag, gate an apply on it, record what runs (T-4955).

    scripts/release.py cut major|minor|patch [--push]   # from main as it is on origin
    scripts/release.py verify [<rev>]                    # prints the release tag of <rev>, or refuses
    scripts/release.py record <namespace> <environment>  # writes the ConfigMap jc-release
    scripts/release.py show <namespace>                  # prints it, for the smoke
    scripts/release.py changelog [--check]               # CHANGELOG.md from releases/*.md

A release is an annotated tag `vX.Y.Z` on a commit of main that carries `releases/vX.Y.Z.md`
(scripts/release-notes.py) and the CHANGELOG.md section rendered from it. CHANGELOG.md holds
nothing of its own: `changelog --check` (tests/test_release.py) fails when it differs from the
notes. `just prod-apply` applies only a commit `verify` accepts; a rollback applies the previous
tag the same way. Tags are never moved or force-pushed.
"""

from __future__ import annotations

import argparse
import getpass
import importlib.util
import json
import re
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
VERSION = re.compile(r"^v(\d+)\.(\d+)\.(\d+)(-[0-9A-Za-z.-]+)?$")
TASK = re.compile(r"\bT-\d{3,5}\b")
RECORD = "jc-release"
# The images the platform's own repositories build: the CHANGELOG names their digests.
OWN_IMAGES = {"platform": "/joinedcontext-platform:", "portal": "/joinedcontext-portal:",
              "Antares": "/antares-broker-jc:"}


class Refused(Exception):
    """A precondition does not hold; nothing was changed."""


def git(*args: str, cwd: Path = ROOT, check: bool = True) -> str:
    done = subprocess.run(["git", *args], check=False, cwd=cwd, capture_output=True, text=True)
    if check and done.returncode:
        raise Refused(f"git {' '.join(args)}: {done.stderr.strip()}")
    return done.stdout.strip()


def notes_module():
    spec = importlib.util.spec_from_file_location("release_notes", ROOT / "scripts/release-notes.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def bump(previous: str | None, part: str) -> str:
    """The next version after `previous` (a prerelease suffix is dropped first); v0.1.0 when
    there is none."""
    if previous is None:
        return "v0.1.0"
    m = VERSION.match(previous)
    if not m:
        raise Refused(f"{previous!r} is not v<major>.<minor>.<patch>")
    major, minor, patch = (int(x) for x in m.groups()[:3])
    if part == "major":
        return f"v{major + 1}.0.0"
    if part == "minor":
        return f"v{major}.{minor + 1}.0"
    if part == "patch":
        return f"v{major}.{minor}.{patch + 1}"
    raise Refused(f"{part!r} is not major, minor or patch")


def read_notes(path: Path) -> tuple[dict, str]:
    text = path.read_text()
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.DOTALL)
    if not m:
        raise Refused(f"{path.name} has no front matter")
    return yaml.safe_load(m.group(1)) or {}, m.group(2)


def section(meta: dict, body: str) -> str:
    """One CHANGELOG section: version, date, the tasks the commits name, our own images."""
    head = f"## {meta['version']}"
    if meta.get("date"):
        head += f" ({meta['date']})"
    tasks = sorted(set(TASK.findall(body)), key=lambda t: int(t[2:]))
    since = meta.get("previous") or "the first commit"
    link = f"[releases/{meta['version']}.md](releases/{meta['version']}.md)"
    lines = [head, "", f"Since {since}; notes: {link}.", ""]
    lines.append(f"Tasks: {', '.join(tasks)}" if tasks else "Tasks: none")
    lines.append("")
    for name, needle in OWN_IMAGES.items():
        pins = [image for image in meta.get("images") or [] if needle in image]
        lines.append(f"- {name}: " + (", ".join(f"`{p}`" for p in pins) or "not pinned"))
    return "\n".join(lines) + "\n"


def changelog(releases: Path) -> str:
    entries = []
    for path in releases.glob("v*.md"):
        m = VERSION.match(path.stem)
        if m:
            entries.append(((tuple(int(x) for x in m.groups()[:3]), m.group(4) is None), path))
    out = ["# Changelog", "",
           "Generated by `scripts/release.py changelog` from `releases/*.md`; never edited by hand.", ""]
    for _, path in sorted(entries, reverse=True):
        out.append(section(*read_notes(path)))
    return "\n".join(out)


def clean(cwd: Path) -> None:
    dirty = git("status", "--porcelain", "--untracked-files=no", cwd=cwd)
    if dirty:
        raise Refused(f"the working tree has uncommitted changes:\n{dirty}")


def cut(part: str, push: bool, cwd: Path = ROOT, today: str | None = None) -> str:
    clean(cwd)
    git("fetch", "--quiet", "--tags", "origin", "main", cwd=cwd)
    head, main = git("rev-parse", "HEAD", cwd=cwd), git("rev-parse", "origin/main", cwd=cwd)
    if head != main:
        raise Refused(f"HEAD {head[:12]} is not origin/main {main[:12]}: a release is cut from main as pushed")
    tags = git("tag", "--list", "v*", "--sort=-v:refname", "--merged", "HEAD", cwd=cwd).split()
    previous = next((t for t in tags if VERSION.match(t)), None)
    version = bump(previous, part)
    if git("tag", "--list", version, cwd=cwd):
        raise Refused(f"{version} exists already; a tag is never moved")
    notes = notes_module()
    queue = cwd / "releases/next.yaml"
    steps = ((yaml.safe_load(queue.read_text()) or {}).get("steps") or []) if queue.exists() else []
    for step in steps:
        if not isinstance(step, dict) or set(step) != {"name", "run"} or not (cwd / str(step["run"])).is_file():
            raise Refused(f"releases/next.yaml: {step!r} is not {{name, run}} naming a script")
    subjects = git("log", "--no-merges", "--format=%s", f"{previous}..HEAD" if previous else "HEAD",
                   cwd=cwd).splitlines()
    date = today or f"{datetime.now(UTC):%Y-%m-%d}"
    text = notes.notes(version, previous, notes.images(cwd / "components"), steps, subjects, date)
    (cwd / f"releases/{version}.md").write_text(text)
    queue.write_text("---\n# Steps the next release runs after its apply, {name, run} each.\nsteps: []\n")
    (cwd / "CHANGELOG.md").write_text(changelog(cwd / "releases"))
    git("add", f"releases/{version}.md", "releases/next.yaml", "CHANGELOG.md", cwd=cwd)
    git("commit", "--quiet", "-m", f"release {version}", cwd=cwd)
    tasks = len(set(TASK.findall("\n".join(subjects))))
    git("tag", "--annotate", version, "-m", f"release {version}: {tasks} tasks since {previous or 'the start'}",
        cwd=cwd)
    pushing = ["push", "--atomic", "origin", "HEAD:refs/heads/main", f"refs/tags/{version}"]
    if push:
        git(*pushing, cwd=cwd)
    else:
        print(f"cut {version}; publish it with: git {' '.join(pushing)}")
    return version


def verify(rev: str = "HEAD", cwd: Path = ROOT) -> str:
    """The release tag `rev` is: an annotated vX.Y.Z tag on exactly that commit, the same on
    origin, with a clean working tree. Anything else is refused."""
    clean(cwd)
    sha = git("rev-parse", "--verify", "--quiet", f"{rev}^{{commit}}", cwd=cwd)
    tags = [t for t in git("tag", "--points-at", sha, "--list", "v*", cwd=cwd).split() if VERSION.match(t)]
    annotated = [t for t in tags if git("cat-file", "-t", f"refs/tags/{t}", cwd=cwd) == "tag"]
    if not annotated:
        found = f" (lightweight {', '.join(tags)})" if tags else ""
        raise Refused(f"{sha[:12]} carries no annotated release tag vX.Y.Z{found}: prod applies only a "
                      "release; cut one with `just release patch` or check out the tag to roll back to")
    tag = max(annotated, key=lambda t: tuple(int(x) for x in VERSION.match(t).groups()[:3]))
    local = git("rev-parse", f"refs/tags/{tag}", cwd=cwd)
    remote = git("ls-remote", "--tags", "origin", f"refs/tags/{tag}", cwd=cwd).split()
    if not remote or remote[0] != local:
        raise Refused(f"{tag} is not on origin as it is here: push the tag (never force) before applying it")
    return tag


def kubectl(*args: str, stdin: str | None = None) -> str:
    done = subprocess.run(["kubectl", *args], check=False, input=stdin, capture_output=True, text=True)
    if done.returncode:
        raise Refused(f"kubectl {' '.join(args)}: {done.stderr.strip()}")
    return done.stdout


def record(namespace: str, environment: str, cwd: Path = ROOT) -> dict:
    sha = git("rev-parse", "HEAD", cwd=cwd)
    tags = [t for t in git("tag", "--points-at", sha, "--list", "v*", cwd=cwd).split() if VERSION.match(t)]
    who = git("config", "user.email", cwd=cwd, check=False) or getpass.getuser()
    data = {"version": tags[-1] if tags else "untagged", "commit": sha,
            "describe": git("describe", "--tags", "--always", "--dirty", cwd=cwd),
            "environment": environment, "appliedBy": who,
            "appliedAt": f"{datetime.now(UTC):%Y-%m-%dT%H:%M:%SZ}"}
    manifest = {"apiVersion": "v1", "kind": "ConfigMap",
                "metadata": {"name": RECORD, "namespace": namespace,
                             "labels": {"app.kubernetes.io/part-of": "joinedcontext",
                                        "app.kubernetes.io/managed-by": "release.py"}},
                "data": data}
    kubectl("apply", "-f", "-", stdin=json.dumps(manifest))
    return data


def show(namespace: str) -> str:
    try:
        data = json.loads(kubectl("-n", namespace, "get", "configmap", RECORD, "-o", "json")).get("data") or {}
    except (Refused, OSError, ValueError):
        return f"release: none recorded in {namespace} ({RECORD} not readable)"
    return (f"release: {data.get('version', 'unknown')} ({data.get('describe') or data.get('commit', '?')}) "
            f"applied by {data.get('appliedBy', 'unknown')} at {data.get('appliedAt', 'unknown')}")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = p.add_subparsers(dest="command", required=True)
    c = sub.add_parser("cut")
    c.add_argument("part", choices=["major", "minor", "patch"])
    c.add_argument("--push", action="store_true")
    sub.add_parser("verify").add_argument("rev", nargs="?", default="HEAD")
    r = sub.add_parser("record")
    r.add_argument("namespace")
    r.add_argument("environment")
    sub.add_parser("show").add_argument("namespace")
    sub.add_parser("changelog").add_argument("--check", action="store_true")
    args = p.parse_args(argv)
    try:
        if args.command == "cut":
            cut(args.part, args.push)
        elif args.command == "verify":
            print(verify(args.rev))
        elif args.command == "record":
            print(json.dumps(record(args.namespace, args.environment)))
        elif args.command == "show":
            print(show(args.namespace))
        else:
            text = changelog(ROOT / "releases")
            if args.check:
                if (ROOT / "CHANGELOG.md").read_text() != text:
                    raise Refused("CHANGELOG.md differs from releases/*.md: run scripts/release.py changelog")
            else:
                (ROOT / "CHANGELOG.md").write_text(text)
    except Refused as refused:
        print(f"refused: {refused}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
