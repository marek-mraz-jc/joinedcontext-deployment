#!/usr/bin/env python3
"""Writes the catalogue's publish-gate hidden list from the gate's evidence (EP-145, T-4846).

The publish gate (joinedcontext-conformance tests/assistant/publish_gate.py) writes `<out>.json`:
one row per package with its verdict and the state of each check. Every row whose verdict is
`hide` becomes one `hidden:` entry of components/ckan/values/catalogue/development-values.yaml.gotmpl,
the reason being its first failed check, except a package listed in publish-gate-passed-back.yaml
beside it (name: why it passed back in). The block carries the sha256 of its own entries, so
`--verify` (run by tests/test_ckan_hidden_list.py in CI) fails when anyone edits it by hand.

    scripts/ckan-hidden-list.py --gate ../joinedcontext-conformance/evidence/publish-gate-T-4448.json
    scripts/ckan-hidden-list.py --verify
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VALUES = ROOT / "components/ckan/values/catalogue/development-values.yaml.gotmpl"
PASSED_BACK = ROOT / "components/ckan/values/catalogue/publish-gate-passed-back.yaml"
BEGIN = "# BEGIN generated by scripts/ckan-hidden-list.py (EP-145): do not edit by hand"
END = "# END generated hidden list"
ENTRY = re.compile(r"^  ([a-z0-9][a-z0-9_-]*): (.+)$")
DIGEST = re.compile(r"^# gate (\S+), entries sha256:([0-9a-f]{64})$")


def reasons(gate, domain):
    """{package: first failed check and its reason} of every hidden row, in name order. A reason
    names the gate's catalogue host; the values file names the gateway's host of each deployment."""
    out = {}
    for row in gate.get("rows") or []:
        if row.get("verdict") != "hide":
            continue
        failed = [(name, check.get("reason") or "") for name, check in (row.get("checks") or {}).items()
                  if (check or {}).get("state") == "fail"]
        if not failed:
            raise ValueError("%s is hidden without a failed check" % row.get("package"))
        name, reason = failed[0]
        text = "%s: %s" % (name, reason) if reason else name
        if domain:
            text = text.replace("https://%s/" % domain, "https://api.{{ .Values.global.domain }}/")
        out[row["package"]] = text
    return dict(sorted(out.items()))


def passed_back(text):
    """The `name: why` lines of publish-gate-passed-back.yaml; comments and blank lines skipped."""
    out = {}
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        name, sep, why = line.partition(":")
        if not sep or not re.fullmatch(r"[a-z0-9][a-z0-9_-]*", name) or not why.strip():
            raise ValueError("publish-gate-passed-back.yaml: %r is not `name: why`" % line)
        out[name] = why.strip()
    return out


def entries_digest(lines):
    return hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest()


def render(gate, kept, domain):
    """The generated block, markers included."""
    hidden = {name: why for name, why in reasons(gate, domain).items() if name not in kept}
    lines = ["  %s: %s" % (name, json.dumps(why, ensure_ascii=False)) for name, why in hidden.items()]
    at = gate.get("at") or "unknown"
    return "\n".join([BEGIN, "# gate %s, entries sha256:%s" % (at, entries_digest(lines)), "hidden:", *lines, END])


def split(values):
    """(before, block, after) of the values file around the generated block."""
    start, end = values.find(BEGIN), values.find(END)
    if start < 0 or end < start:
        raise ValueError("%s holds no generated hidden list between its markers" % VALUES.name)
    end += len(END)
    return values[:start], values[start:end], values[end:]


def verify(block):
    """Problems of a generated block: the digest must match its entries."""
    lines = block.splitlines()
    match = DIGEST.match(lines[1]) if len(lines) > 3 else None
    if not match or lines[2] != "hidden:":
        return ["the block lost its digest line or its `hidden:` key"]
    entries = lines[3:-1]
    bad = [line for line in entries if not ENTRY.match(line)]
    if bad:
        return ["not an entry: %r" % bad[0]]
    if entries_digest(entries) != match.group(2):
        return ["the hidden list was edited by hand: regenerate it with scripts/ckan-hidden-list.py --gate <evidence>"]
    names = [ENTRY.match(line).group(1) for line in entries]
    if names != sorted(set(names)):
        return ["the entries are not sorted and unique"]
    return []


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--gate", type=Path, help="the publish gate's <out>.json")
    parser.add_argument("--domain", default="dev.joinedcontext.com", help="the gate's catalogue host domain")
    parser.add_argument("--verify", action="store_true", help="check the committed block against its digest")
    args = parser.parse_args()
    values = VALUES.read_text(encoding="utf-8")
    before, block, after = split(values)
    if args.verify:
        problems = verify(block)
        print("\n".join(problems) or "hidden list ok")
        return 1 if problems else 0
    if not args.gate:
        parser.error("--gate or --verify")
    gate = json.loads(args.gate.read_text(encoding="utf-8"))
    kept = passed_back(PASSED_BACK.read_text(encoding="utf-8"))
    VALUES.write_text(before + render(gate, kept, args.domain) + after, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
