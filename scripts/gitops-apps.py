#!/usr/bin/env python3
"""The Applications Argo CD keeps one environment with (ADR-N-054 §2.3, OPS-54).

    python3 scripts/gitops-apps.py dev > gitops/dev.yaml

Reads the assembled deployment (`just _dev-assemble`): `helmfile list` for each enabled release's
component and namespace, and the environment's rendered values for the component order and the
namespace annotations the `prepare` hook writes on a sync. One Application per component and
namespace, its sync wave the component's place in `components:`. The `gitops` component is helmfile's alone: Argo CD never
manages itself, so `just dev-apply` can always rebuild it.
"""

import json
import subprocess
import sys

import yaml

HELMFILE = ["helmfile", "-f", "deployment/helmfile.yaml"]
SELF = "gitops"


def helmfile(env, *args):
    return subprocess.run([*HELMFILE, "-e", env, *args], check=True, capture_output=True, text=True).stdout


def labels(release):
    return dict(pair.split(":", 1) for pair in release["labels"].split(",") if ":" in pair)


def values(env):
    """The environment's rendered values, as the `prepare` state sees them."""
    for state in yaml.load_all(helmfile(env, "build"), Loader=yaml.CSafeLoader):
        if state and state.get("hooks"):
            return state["renderedvalues"]
    sys.exit(f"{env}: no prepare state, so no component order")


def namespace_annotations(mesh):
    """What `components/prepare` annotates each namespace with on a sync."""
    if not (mesh.get("enable") and mesh.get("type") == "linkerd" and mesh.get("patchNamespaces")):
        return {}
    annotations = {"linkerd.io/inject": "enabled"}
    if mesh.get("defaultInboundPolicy"):
        annotations["config.linkerd.io/default-inbound-policy"] = mesh["defaultInboundPolicy"]
    return annotations


def applications(env, releases, rendered):
    """One Application per component and namespace: a component whose releases land in two
    namespaces (the network policies of another component's namespace) gets one for each, so
    every object without a namespace of its own lands where helmfile would put it."""
    order = rendered.get("components") or []
    namespaces = {}
    for release in releases:
        component = labels(release).get("component")
        if not release["enabled"] or component == SELF:
            continue
        if component not in order:
            sys.exit(f"{release['name']}: component {component!r} is not in the {env} components list")
        namespaces.setdefault(component, set()).add(release["namespace"])
    return [
        {"name": c if len(namespaces[c]) == 1 else f"{c}-{n}", "component": c, "namespace": n, "wave": order.index(c)}
        for c in order if c in namespaces
        for n in sorted(namespaces[c])
    ]


def main(env):
    releases = json.loads(helmfile(env, "list", "--output", "json"))
    rendered = values(env)
    document = {
        "environment": env,
        "namespaceAnnotations": namespace_annotations(rendered.get("global", {}).get("serviceMesh") or {}),
        "components": applications(env, releases, rendered),
    }
    print(f"# Generated by `python3 scripts/gitops-apps.py {env}` from the assembled deployment; regenerate, never")
    print("# edit (docs Deployment/15-gitops.md §2). One Argo CD Application per component and namespace, in wave order.")
    print(yaml.safe_dump(document, sort_keys=False, default_flow_style=None, width=120), end="")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: gitops-apps.py <environment>")
    main(sys.argv[1])
