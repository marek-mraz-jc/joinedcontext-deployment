def memory(cells: int) -> int:
    """The runner's memory for a topic, by its largest cube: about 2 kB per decoded cell."""
    # ponytail: a linear guess from the cell count; at CUBE_LIMIT it is 128 MB above the floor.
    return min(2048, max(128, -(-cells * 2 // 1024 // 64) * 64 + 128))


