def role(note: str | None) -> str:
    n = (note or "").strip()
    if n in PERIOD:
        return "period"
    if n.startswith("0 SR") or n in AREA:
        return "area"
    if n in INDICATOR:
        return "indicator"
    if n in UNIT:
        return "unit"
    return "key"


def roles(dimensions: dict) -> dict:
    """The cube's dimension per role: the first of each role, every other dimension a key, in order."""
    out = {"period": None, "area": None, "indicator": None, "unit": None, "keys": []}
    for name, d in dimensions.items():
        r = role(d.get("note"))
        if r != "key" and out[r] is None:
            out[r] = name
        else:
            out["keys"].append(name)
    return out


def code_of(item: dict) -> str | None:
    m = CODE.search(item.get("href", ""))
    return m.group(1) if m else None


def label(text: str | None) -> str | None:
    """The collection's label, or None for a missing one or the placeholder "Default"."""
    text = " ".join((text or "").split())
    return text if text and text != "Default" else None


def datasets(collection_sk: dict, collection_en: dict) -> list[dict]:
    """Every dataset of the collection: its code, labels (sk falls back to en, en to sk, both to
    the theme's name: the ps cubes have none), last update and dimensions in the order the
    dataset URL takes them."""
    en = {code_of(i): label(i.get("label")) for i in collection_en["link"]["item"]}
    out = []
    for item in collection_sk["link"]["item"]:
        code = code_of(item)
        if code is None:
            continue
        sk = label(item.get("label"))
        theme = THEMES.get(code[:2], ({"sk": code, "en": code},))[0]
        out.append({"code": code, "theme": code[:2], "update": item.get("update") or "",
                    "title": {"sk": sk or en.get(code) or theme["sk"], "en": en.get(code) or sk or theme["en"]},
                    "dimensions": item.get("dimension") or {}})
    return out


def themes(items: list[dict], since: str = RECENT, minimum: int = MIN_RECENT) -> dict[str, list[dict]]:
    """theme -> its datasets updated since `since`, for themes with at least `minimum` of them and
    a name in THEMES; a cube with no period dimension is left out, nothing could date its cells."""
    by: dict[str, list[dict]] = {}
    for d in items:
        if d["update"] >= since and roles(d["dimensions"])["period"]:
            by.setdefault(d["theme"], []).append(d)
    return {t: sorted(v, key=lambda d: d["code"]) for t, v in sorted(by.items()) if len(v) >= minimum and t in THEMES}


def fetch(url: str, cache: Path | None, waits=(5, 30)) -> dict:
    """GET `url` as JSON, from the cache when it holds it; a 5xx or a network error is retried."""
    path = cache / (hashlib.sha256(url.encode()).hexdigest() + ".json") if cache else None
    if path and path.exists():
        return json.loads(path.read_text())
    for attempt in range(len(waits) + 1):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"Accept": "application/json"}), timeout=60) as r:
                body = r.read()
            break
        except urllib.error.HTTPError as e:
            if e.code < 500 or attempt == len(waits):
                raise
        except (urllib.error.URLError, TimeoutError, ConnectionError):
            if attempt == len(waits):
                raise
        time.sleep(waits[attempt])
    data = json.loads(body)
    if path:
        path.write_bytes(body)
    return data


def sizes(themed: dict[str, list[dict]], get) -> dict[str, int]:
    """code -> the cube's cell count, the product of its dimensions' category counts."""
    jobs = {(d["code"], name): f"{API}/dimension/{d['code']}/{name}?lang=sk&type=json"
            for ds in themed.values() for d in ds for name in d["dimensions"]}
    with concurrent.futures.ThreadPoolExecutor(4) as pool:
        counts = dict(zip(jobs, pool.map(lambda u: len(get(u).get("category", {}).get("index") or {}), jobs.values())))
    out: dict[str, int] = {}
    for (code, _), n in counts.items():
        out[code] = out.get(code, 1) * n
    return out


def cut(themed: dict[str, list[dict]], cells: dict[str, int], limit: int = CUBE_LIMIT) -> tuple[dict[str, list[dict]], list[dict]]:
    """The themes with only their cubes of at most `limit` cells (a theme left with none goes),
    and the cubes left out."""
    kept = {t: [d for d in ds if cells.get(d["code"], 0) <= limit] for t, ds in themed.items()}
    return {t: ds for t, ds in kept.items() if ds}, [d for ds in themed.values() for d in ds if cells.get(d["code"], 0) > limit]


def dataset_url(d: dict) -> str:
    """The whole cube: `all` for every dimension the collection lists, in its order."""
    return f"{API}/dataset/{d['code']}/" + "/".join("all" for _ in d["dimensions"]) + "?lang=sk&type=json"


def q(value) -> str:
    """A YAML scalar: JSON's double-quoted string is one."""
    return json.dumps(value, ensure_ascii=False)


def title(t: dict) -> str:
    return "{ sk: %s, en: %s }" % (q(t["sk"][:120]), q(t["en"][:120]))


def slug_for(path: Path) -> str:
    """The Endpoint's slug: kept from the committed file, minted once (EP-02)."""
    if path.exists():
        m = re.search(r"^  slug: ([a-z2-7]+)$", path.read_text(), re.M)
        if m:
            return m.group(1)
    return base64.b32encode(secrets.token_bytes(20)).decode().lower().rstrip("=")


def decoder(ds: list[dict]) -> str:
    """The bloblang of the theme's pipeline: the JSON-stat 2.0 decoder of the zilina cube streams
    (zilina-pipeline-obyvatelstvo-bento.yaml), over a table of the theme's cubes and their roles."""
    table = {d["code"]: {"update": d["update"], **roles(d["dimensions"]), "source": dataset_url(d)} for d in ds}
    return f"""# The cubes of this theme and the role of their dimensions, read from DATAcube's collection.
let cubes = {json.dumps(table, ensure_ascii=False, sort_keys=True)}
# The cube a message is, from the address the answer names itself by.
let cube = this.href.or("").re_find_object("/(?P<code>[a-z]{{2}}[0-9]{{4}}[a-z]{{2}})/").code.catch(null)
let roles = $cubes.get($cube.or("")).catch(null)
root = if $roles == null {{ throw("no cube of this theme answered: %v".format(this.href.or("no href"))) }} else if this.value.or([]).length() == 0 {{ throw("cube %v answered no cell".format($cube)) }} else {{ this }}
let ds = this
let ids = this.id
let sizes = this.size
let n = $sizes.length()
# JSON-stat 2.0 is decoded by the index and never by the order: the period comes newest first.
let codes = $ids.map_each(d -> $ds.dimension.get(d).category.index.key_values().sort_by(kv -> kv.value).map_each(kv -> kv.key))
let labels = $ids.map_each(d -> $ds.dimension.get(d).category.label.or({{}}))
let strides = range(0, $n, 1).map_each(k -> if k + 1 >= $n {{ 1 }} else {{ $sizes.slice(k + 1, $n).fold(1, t -> t.tally * t.value) }})
let at_index = range(0, $n, 1).map_each(k -> {{ $ids.index(k): k }}).squash()
# A dimension DATAcube adds to the answer only (`*_data`, one value) names nothing.
let named = [$roles.period, $roles.area, $roles.indicator, $roles.unit].concat($roles.keys)
let keys = $roles.keys.concat($ids.filter(d -> !$named.contains(d) && $sizes.index($at_index.get(d)) > 1))
let updated = ($ds.update.or($roles.update)).ts_parse("2006-01-02").ts_format("2006-01-02T15:04:05Z07:00", "UTC").catch(null)
let cells = if $ds.value.type() == "object" {{ $ds.value.key_values().map_each(kv -> {{ "p": kv.key.number().int64(), "v": kv.value }}) }} else {{ range(0, $ds.value.length(), 1).map_each(p -> {{ "p": p, "v": $ds.value.index(p) }}) }}
# One entity per cell that carries a number; a cell the publisher left empty is not a zero.
root = $cells.filter(c -> c.v != null && c.v.type() == "number").map_each(c -> range(0, $n, 1).map_each(k -> {{ $ids.index(k): $codes.index(k).index(((c.p / $strides.index(k)).floor().int64()) % $sizes.index(k)) }}).squash().merge({{ "_v": c.v }})).map_each(at -> {{
  "id": "urn:ngsi-ld:%v:%v:%v:%v".format("{TYPE}", env("JC_ORG_DOMAIN"), env("JC_SPACE"), [$cube, if $roles.area == null {{ "SK0" }} else {{ at.get($roles.area) }}, at.get($roles.period), if $roles.indicator == null {{ $cube }} else {{ at.get($roles.indicator) }}].concat($keys.map_each(d -> at.get(d))).concat(if $roles.unit == null {{ [] }} else {{ [at.get($roles.unit)] }}).join("-").re_replace_all("[^A-Za-z0-9._~-]", "_")),
  "type": "{TYPE}",
  "dataSet": {{ "type": "Property", "value": $cube }},
  "indicator": {{ "type": "Property", "value": if $roles.indicator == null {{ $cube }} else {{ at.get($roles.indicator) }} }},
  "refArea": {{ "type": "Property", "value": if $roles.area == null {{ "SK0" }} else {{ at.get($roles.area) }} }},
  "refPeriod": {{ "type": "Property", "value": at.get($roles.period) }},
  "dimensionKey": if $keys.length() == 0 {{ null }} else {{ {{ "type": "Property", "value": $keys.map_each(d -> at.get(d)).join("-") }} }},
  "kpiValue": {{ "type": "Property", "value": at._v, "observedAt": $updated }}.filter(e -> e.value != null),
  "unitText": if $roles.unit == null {{ null }} else {{ {{ "type": "Property", "value": $labels.index($at_index.get($roles.unit)).get(at.get($roles.unit)).or(at.get($roles.unit)) }} }},
  "source": {{ "type": "Property", "value": $roles.source }},
  "isPartOf": {{ "type": "Property", "value": "{CKAN}/dataset/susr-%v".format($cube) }},
  "dateObserved": if $updated == null {{ null }} else {{ {{ "type": "Property", "value": $updated }} }}
}}.filter(e -> e.value != null))
"""


def memory(cells: int) -> int:
    """The runner's memory for a theme, by its largest cube: about 2 kB per decoded cell."""
    # ponytail: a linear guess from the cell count; measure a real run before T-4391 applies the largest themes.
    return min(2048, max(128, -(-cells * 2 // 1024 // 64) * 64 + 128))


