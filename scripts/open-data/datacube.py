def render(themed: dict[str, list[dict]], cells: dict[str, int], seed: Path) -> tuple[dict[Path, str], dict]:
    """Every file of every theme folder, and the od-datasets.json entries of their datasets."""
    out: dict[Path, str] = {}
    rows = {}
    for i, (theme, ds) in enumerate(themed.items()):
        folder = seed / f"susr-{theme}"
        slug = slug_for(folder / "endpoint.yaml")
        for name, text in theme_files(theme, ds, cells, slug, i).items():
            out[folder / name] = text
        for f in MODEL_FILES:
            out[folder / f] = (MODEL / f).read_text()
        for d in ds:
            rows[f"susr-{d['code']}"] = {"endpoint": slug, "type": TYPE, "dataset": f"{CKAN}/dataset/susr-{d['code']}",
                                         "location": False, "filtered": True}
    return out, rows


def distributions(committed: dict, rows: dict) -> str:
    """od-datasets.json with the susr- rows replaced by `rows`, in generate.py's layout, which
    keeps them as committed when it writes the file's other rows."""
    out = {k: v for k, v in committed.items() if not k.startswith("susr-")} | rows
    return "{\n" + ",\n".join(f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}" for k, v in sorted(out.items())) + "\n}\n"


def table(themed: dict[str, list[dict]], cells: dict[str, int]) -> str:
    lines = ["| theme | datasets | cells (entities, at most) | largest cube | maxMemoryMb |", "|---|---:|---:|---|---:|"]
    total_d = total_c = 0
    for theme, ds in themed.items():
        n = sum(cells.get(d["code"], 0) for d in ds)
        big = max(ds, key=lambda d: cells.get(d["code"], 0))
        lines.append(f"| {theme} | {len(ds)} | {n:,} | {big['code']} ({cells.get(big['code'], 0):,}) | {memory(cells.get(big['code'], 0))} |")
        total_d, total_c = total_d + len(ds), total_c + n
    lines.append(f"| **all {len(themed)}** | **{total_d}** | **{total_c:,}** | | |")
    return "\n".join(lines)


def main(argv: list[str]) -> None:
    cache = Path(argv[argv.index("--cache") + 1]) if "--cache" in argv else None
    if cache:
        cache.mkdir(parents=True, exist_ok=True)
    get = lambda url: fetch(url, cache)  # noqa: E731
    themed = themes(datasets(get(f"{API}/collection?lang=sk"), get(f"{API}/collection?lang=en")))
    cells = sizes(themed, get)
    themed, left = cut(themed, cells)
    files, rows = render(themed, cells, SEED)
    for folder in {p.parent for p in files}:
        if folder.exists():
            shutil.rmtree(folder)
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    DISTRIBUTIONS.write_text(distributions(json.loads(DISTRIBUTIONS.read_text()), rows))
    print(table(themed, cells))
    print(f"\nLeft out, over {CUBE_LIMIT:,} cells: " + ", ".join(f"{d['code']} ({cells[d['code']]:,})" for d in sorted(left, key=lambda d: d["code"])))


if __name__ == "__main__":
    main(sys.argv[1:])
