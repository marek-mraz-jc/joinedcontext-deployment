# A dimension's role, read from its collection `note` (the JSON-stat `role` is unreliable: the
# ps cubes mark the sex as time). The first match wins; any other dimension is a key.
PERIOD = ("Rok", "Roky", "Štvrťrok", "Mesiac", "Obdobie", "Časové obdobie", "Týždeň", "Stav ku dňu")
